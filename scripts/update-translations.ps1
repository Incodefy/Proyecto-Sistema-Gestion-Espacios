# Idiomas restantes con traducciones en inglés como fallback
$fallbackLanguages = @("fa", "jv", "mr", "nl", "pa", "pl", "ta", "te", "th", "tr", "ur", "vi")

Write-Host "Actualizando archivos de traducción..." -ForegroundColor Green

foreach ($lang in $translations.Keys) {
    $filePath = "F:\Descargas\Git\Proyecto-Hospital-Padre-Hurtado\incodefy\locales\$lang.json"
    
    if (Test-Path $filePath) {
        $content = Get-Content $filePath -Raw | ConvertFrom-Json
        
        # Agregar color_picker si no existe
        if (-not $content.profile.PSObject.Properties['color_picker']) {
            $content.profile | Add-Member -MemberType NoteProperty -Name 'color_picker' -Value ([PSCustomObject]@{
                current_color = $translations[$lang]["current_color"]
                preview_aria = $translations[$lang]["preview_aria"]
                open_picker_aria = $translations[$lang]["open_picker_aria"]
                explore_colors = $translations[$lang]["explore_colors"]
                select_color = $translations[$lang]["select_color"]
                select_a_color = $translations[$lang]["select_a_color"]
                search_placeholder = $translations[$lang]["search_placeholder"]
                apply_color = $translations[$lang]["apply_color"]
                categories = [PSCustomObject]@{
                    popular = $translations[$lang]["popular"]
                    vibrant = $translations[$lang]["vibrant"]
                    pastel = $translations[$lang]["pastel"]
                    dark = $translations[$lang]["dark"]
                }
            })
        }
        
        # Agregar loading_groups
        if (-not $content.profile.workspace.PSObject.Properties['loading_groups']) {
            $content.profile.workspace | Add-Member -MemberType NoteProperty -Name 'loading_groups' -Value $translations[$lang]["loading_groups"]
        }
        
        # Guardar
        $content | ConvertTo-Json -Depth 10 | Set-Content $filePath -Encoding UTF8
        Write-Host "✓ Actualizado: $lang.json" -ForegroundColor Cyan
    }
}

